-- Streamlit in Snowflake workbench on the container runtime with restricted caller's rights.
-- Files are uploaded by scripts/deploy_streamlit.sh. Caller grants need MANAGE CALLER GRANTS (ACCOUNTADMIN).
-- Packages (requirements.txt) come from Snowflake's built-in PyPI mirror; no internet egress integration needed.
USE ROLE ACCOUNTADMIN;
GRANT DATABASE ROLE SNOWFLAKE.PYPI_REPOSITORY_USER TO ROLE ATTENDEE_ROLE;

USE ROLE ATTENDEE_ROLE;
CREATE STAGE IF NOT EXISTS TRULINE.APP.STREAMLIT_STAGE DIRECTORY = (ENABLE = TRUE) COMMENT = 'Workbench source files';

CREATE OR REPLACE STREAMLIT TRULINE.APP.COVERAGE_WORKBENCH
  FROM '@TRULINE.APP.STREAMLIT_STAGE/workbench'
  MAIN_FILE = 'streamlit_app.py'
  RUNTIME_NAME = 'SYSTEM$ST_CONTAINER_RUNTIME_PY3_11'
  COMPUTE_POOL = SYSTEM_COMPUTE_POOL_CPU
  QUERY_WAREHOUSE = DEFAULT_WH
  ARTIFACT_REPOSITORIES = (snowflake.snowpark.pypi_shared_repository)
  TITLE = 'Truline coverage'
  COMMENT = 'PAM workbench: weekly plan, briefs, long tail, audit';
-- The CREATE parameter alone did not take effect in testing; setting it again makes the runtime use the mirror.
ALTER STREAMLIT TRULINE.APP.COVERAGE_WORKBENCH SET ARTIFACT_REPOSITORIES = (snowflake.snowpark.pypi_shared_repository);

GRANT USAGE ON STREAMLIT TRULINE.APP.COVERAGE_WORKBENCH TO ROLE TRULINE_PAM;
GRANT USAGE ON STREAMLIT TRULINE.APP.COVERAGE_WORKBENCH TO ROLE TRULINE_PARTNER;
GRANT USAGE ON STREAMLIT TRULINE.APP.COVERAGE_WORKBENCH TO ROLE TRULINE_OPS;

-- What the app may do with the viewer's privileges (the viewer still needs the privilege themselves).
USE ROLE ACCOUNTADMIN;
GRANT CALLER USAGE ON DATABASE TRULINE TO ROLE ATTENDEE_ROLE;
GRANT CALLER USAGE ON SCHEMA TRULINE.APP TO ROLE ATTENDEE_ROLE;
GRANT CALLER USAGE ON SCHEMA TRULINE.CORE TO ROLE ATTENDEE_ROLE;
GRANT CALLER USAGE ON WAREHOUSE DEFAULT_WH TO ROLE ATTENDEE_ROLE;
GRANT INHERITED CALLER SELECT ON ALL VIEWS IN SCHEMA TRULINE.APP TO ROLE ATTENDEE_ROLE;
GRANT INHERITED CALLER USAGE ON ALL PROCEDURES IN SCHEMA TRULINE.APP TO ROLE ATTENDEE_ROLE;
GRANT INHERITED CALLER INSERT ON ALL TABLES IN SCHEMA TRULINE.CORE TO ROLE ATTENDEE_ROLE;
GRANT CALLER SELECT ON SEMANTIC VIEW TRULINE.APP.TRULINE_COVERAGE TO ROLE ATTENDEE_ROLE;
