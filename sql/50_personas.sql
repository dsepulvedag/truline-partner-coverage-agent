-- Personas: one real Snowflake user per persona (no app-side impersonation). Run with ACCOUNTADMIN available.
-- Users are created WITHOUT passwords; set them yourself in Snowsight (Admin > Users & roles) before logging in.
USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS TRULINE_PAM COMMENT = 'Truline partner account managers (dedicated and shared)';
CREATE ROLE IF NOT EXISTS TRULINE_PARTNER COMMENT = 'Reseller partner users (own accounts only, internal fields masked)';
CREATE ROLE IF NOT EXISTS TRULINE_OPS COMMENT = 'Truline coverage operations (long tail, all partners, full audit)';

CREATE USER IF NOT EXISTS FATIMA_HAYES DISPLAY_NAME = 'Fatima Hayes (dedicated PAM)' TYPE = PERSON
  DEFAULT_ROLE = TRULINE_PAM DEFAULT_WAREHOUSE = DEFAULT_WH DEFAULT_NAMESPACE = TRULINE.APP
  COMMENT = 'Dedicated PAM TP001 (1 top-50 partner)';
CREATE USER IF NOT EXISTS NOAH_SHELBY DISPLAY_NAME = 'Noah Shelby (shared PAM)' TYPE = PERSON
  DEFAULT_ROLE = TRULINE_PAM DEFAULT_WAREHOUSE = DEFAULT_WH DEFAULT_NAMESPACE = TRULINE.APP
  COMMENT = 'Shared PAM TP054 (19 partners)';
CREATE USER IF NOT EXISTS VERTEX_PARTNER DISPLAY_NAME = 'Vertex Digital Consulting (partner)' TYPE = PERSON
  DEFAULT_ROLE = TRULINE_PARTNER DEFAULT_WAREHOUSE = DEFAULT_WH DEFAULT_NAMESPACE = TRULINE.APP
  COMMENT = 'Long-tail partner P0370, no PAM';
CREATE USER IF NOT EXISTS COVERAGE_OPS DISPLAY_NAME = 'Coverage ops' TYPE = PERSON
  DEFAULT_ROLE = TRULINE_OPS DEFAULT_WAREHOUSE = DEFAULT_WH DEFAULT_NAMESPACE = TRULINE.APP
  COMMENT = 'Truline coverage operations';

GRANT ROLE TRULINE_PAM TO USER FATIMA_HAYES;
GRANT ROLE TRULINE_PAM TO USER NOAH_SHELBY;
GRANT ROLE TRULINE_PARTNER TO USER VERTEX_PARTNER;
GRANT ROLE TRULINE_OPS TO USER COVERAGE_OPS;

EXECUTE IMMEDIATE $$
DECLARE
  roles ARRAY DEFAULT ARRAY_CONSTRUCT('TRULINE_PAM', 'TRULINE_PARTNER', 'TRULINE_OPS');
BEGIN
  FOR i IN 0 TO ARRAY_SIZE(roles) - 1 DO
    LET r VARCHAR := roles[i];
    EXECUTE IMMEDIATE 'GRANT USAGE ON WAREHOUSE DEFAULT_WH TO ROLE ' || r;
    EXECUTE IMMEDIATE 'GRANT USAGE ON DATABASE TRULINE TO ROLE ' || r;
    EXECUTE IMMEDIATE 'GRANT USAGE ON SCHEMA TRULINE.APP TO ROLE ' || r;
    EXECUTE IMMEDIATE 'GRANT USAGE ON SCHEMA TRULINE.CORE TO ROLE ' || r;
    EXECUTE IMMEDIATE 'GRANT SELECT ON ALL VIEWS IN SCHEMA TRULINE.APP TO ROLE ' || r;
    EXECUTE IMMEDIATE 'GRANT SELECT ON FUTURE VIEWS IN SCHEMA TRULINE.APP TO ROLE ' || r;
    EXECUTE IMMEDIATE 'GRANT SELECT ON SEMANTIC VIEW TRULINE.APP.TRULINE_COVERAGE TO ROLE ' || r;
    EXECUTE IMMEDIATE 'GRANT USAGE ON ALL PROCEDURES IN SCHEMA TRULINE.APP TO ROLE ' || r;
    EXECUTE IMMEDIATE 'GRANT USAGE ON FUTURE PROCEDURES IN SCHEMA TRULINE.APP TO ROLE ' || r;
    EXECUTE IMMEDIATE 'GRANT INSERT ON TABLE TRULINE.CORE.PLAYS TO ROLE ' || r;
    EXECUTE IMMEDIATE 'GRANT INSERT ON TABLE TRULINE.CORE.AUDIT_LOG TO ROLE ' || r;
    EXECUTE IMMEDIATE 'GRANT INSERT ON TABLE TRULINE.CORE.DOC_FACTS TO ROLE ' || r;
    EXECUTE IMMEDIATE 'GRANT INSERT ON TABLE TRULINE.CORE.DOCUMENTS TO ROLE ' || r;
    EXECUTE IMMEDIATE 'GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE ' || r;
  END FOR;
  RETURN 'granted';
END;
$$;

USE ROLE ATTENDEE_ROLE;
MERGE INTO TRULINE.CORE.USER_SCOPE t USING (
  SELECT * FROM VALUES
    ('FATIMA_HAYES', 'Dedicated PAM', 'PAM', 'TP001', NULL),
    ('NOAH_SHELBY', 'Shared PAM', 'PAM', 'TP054', NULL),
    ('VERTEX_PARTNER', 'Partner', 'PARTNER', NULL, 'P0370'),
    ('COVERAGE_OPS', 'Coverage ops', 'ALL', NULL, NULL),
    ('USER', 'Admin', 'ALL', NULL, NULL)
  AS v(USER_NAME, PERSONA, SCOPE, PAM_ID, PARTNER_ID)) s ON t.USER_NAME = s.USER_NAME
WHEN MATCHED THEN UPDATE SET PERSONA = s.PERSONA, SCOPE = s.SCOPE, PAM_ID = s.PAM_ID, PARTNER_ID = s.PARTNER_ID
WHEN NOT MATCHED THEN INSERT VALUES (s.USER_NAME, s.PERSONA, s.SCOPE, s.PAM_ID, s.PARTNER_ID);
