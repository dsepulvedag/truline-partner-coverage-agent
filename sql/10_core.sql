-- Shared core (internal layer). Run as ATTENDEE_ROLE.
-- CORE holds dynamic tables, write tables and the user-scope map. Personas never SELECT from CORE;
-- they read the secure, policy-protected views in APP (20_app.sql). SIM_* columns stop here.
CREATE SCHEMA IF NOT EXISTS TRULINE.CORE;
USE SCHEMA TRULINE.CORE;

-- Tunable play-rule thresholds (CLAUDE.md "Play rules"); the dynamic tables read them.
CREATE TABLE IF NOT EXISTS PLAY_PARAMS (PARAM VARCHAR PRIMARY KEY, VALUE FLOAT, DESCRIPTION VARCHAR);
MERGE INTO PLAY_PARAMS t USING (
  SELECT * FROM VALUES
    ('HEALTH_DROP_THRESHOLD', -15, 'Renewal rescue: HEALTH_SCORE_CHANGE_3M at or below this'),
    ('LOW_UTIL_THRESHOLD', 0.60, 'Proactive right-size: seat utilization below this'),
    ('HIGH_UTIL_THRESHOLD', 0.90, 'Seat pressure: seat utilization at or above this'),
    ('TARGET_UTIL_AFTER_EXPANSION', 0.80, 'Seats to add = active users / this - current seats'),
    ('SEAT_EXPANSION_WIN_RATE', 0.50, 'Expected value multiplier for seat-pressure plays'),
    ('LOOKALIKE_MIN_PEER_SHARE', 0.50, 'Product gap: share of peers (industry group x segment) owning the product'),
    ('LOOKALIKE_MIN_PEERS', 20, 'Product gap: minimum active peers in the cell'),
    ('LOOKALIKE_WIN_RATE', 0.25, 'Expected value multiplier for look-alike product gaps'),
    ('CREDIT_LATE_CONTRACT_MONTH', 8, 'Below-pace credits at or after this contract month = commit at risk'),
    ('MIN_PLAY_VALUE_USD', 10000, 'Plays below this expected value stay out of the weekly plan'),
    ('ESCALATE_VALUE_USD', 250000, 'Plays above this value escalate to the PAM'),
    ('REP_WEEKLY_PLAY_CAP', 5, 'Plays per rep per week before overflow escalates'),
    ('PARTNER_NRR_FLOOR', 0.95, 'Partner needs PAM intervention when NRR is below this'),
    ('PARTNER_AT_RISK_SHARE_CEIL', 0.20, 'Partner needs PAM intervention when at-risk ARR share is above this')
  AS v(PARAM, VALUE, DESCRIPTION)) s ON t.PARAM = s.PARAM
WHEN NOT MATCHED THEN INSERT VALUES (s.PARAM, s.VALUE, s.DESCRIPTION);

-- One row per account: latest month (Sep 2026) plus ARR 12 months earlier, for NRR/GRR.
CREATE OR REPLACE DYNAMIC TABLE ACCOUNT_CURRENT
  TARGET_LAG = '1 day' WAREHOUSE = DEFAULT_WH REFRESH_MODE = FULL
  COMMENT = 'Account snapshot at the latest month with partner, rep and PAM context; base for metrics and plays'
AS
WITH lm AS (SELECT MAX(MONTH) AS M FROM TRULINE.SYNTH.ACCOUNT_MONTHLY),
cur AS (SELECT am.* FROM TRULINE.SYNTH.ACCOUNT_MONTHLY am JOIN lm ON am.MONTH = lm.M),
prev AS (SELECT am.ACCOUNT_ID, am.END_ARR AS ARR_12M_AGO
         FROM TRULINE.SYNTH.ACCOUNT_MONTHLY am JOIN lm ON am.MONTH = DATEADD(month, -12, lm.M))
SELECT a.ACCOUNT_ID, a.ACCOUNT_NAME, a.DOMAIN, a.IS_REAL_COMPANY, a.INDUSTRY, a.INDUSTRY_GROUP, a.SEGMENT,
       a.EMPLOYEE_BAND, a.COUNTRY, a.REGION, a.CUSTOMER_SINCE, a.STATUS, a.CHURN_MONTH, a.BILLING_MODEL,
       a.PARTNER_ID, p.PARTNER_NAME, p.TIER AS PARTNER_TIER, p.COVERAGE_MODEL, p.PAM_ID, k.PAM_NAME,
       a.PARTNER_REP_ID, r.REP_NAME, r.TITLE AS REP_TITLE, r.EMAIL AS REP_EMAIL,
       lm.M AS AS_OF_MONTH,
       COALESCE(c.END_ARR, 0) AS ARR_NOW, COALESCE(pv.ARR_12M_AGO, 0) AS ARR_12M_AGO,
       c.SEAT_ARR, c.CONSUMPTION_ARR, c.OVERAGE_REVENUE, c.CREDITS_CONSUMED, c.SEATS, c.ACTIVE_USERS,
       c.SEAT_UTILIZATION, c.HEALTH_SCORE, c.HEALTH_SCORE_CHANGE_3M, c.RISK_BAND, c.CHURN_PROB_90D,
       c.DRIVER_1, c.DRIVER_2, c.MONTHS_TO_RENEWAL
FROM TRULINE.SYNTH.ACCOUNTS a
CROSS JOIN lm
JOIN TRULINE.SYNTH.PARTNERS p ON p.PARTNER_ID = a.PARTNER_ID
LEFT JOIN TRULINE.SYNTH.TRULINE_PAMS k ON k.PAM_ID = p.PAM_ID
LEFT JOIN TRULINE.SYNTH.PARTNER_REPS r ON r.REP_ID = a.PARTNER_REP_ID
LEFT JOIN cur c ON c.ACCOUNT_ID = a.ACCOUNT_ID
LEFT JOIN prev pv ON pv.ACCOUNT_ID = a.ACCOUNT_ID
WHERE c.ACCOUNT_ID IS NOT NULL OR pv.ACCOUNT_ID IS NOT NULL;

CREATE OR REPLACE DYNAMIC TABLE CONSUMPTION_CURRENT
  TARGET_LAG = '1 day' WAREHOUSE = DEFAULT_WH REFRESH_MODE = FULL
  COMMENT = 'Credit contracts at the latest month with burn pace, projected shortfall and commit at risk'
AS
SELECT c.MONTH AS AS_OF_MONTH, c.ACCOUNT_ID, c.PARTNER_ID, c.CONTRACT_MONTH, 12 - c.CONTRACT_MONTH AS MONTHS_LEFT,
       c.ANNUAL_COMMIT_CREDITS, c.PRICE_PER_CREDIT_USD, c.COMMIT_ARR, c.CREDITS_USED_CONTRACT_YTD,
       c.CREDITS_REMAINING, c.BURN_PACE, c.BURN_STATUS, c.OVERAGE_CREDITS, c.OVERAGE_REVENUE, c.EXPIRED_CREDITS,
       c.ANNUAL_COMMIT_CREDITS * c.CONTRACT_MONTH / 12 AS EXPECTED_CREDITS_TO_DATE,
       ROUND(GREATEST(0, c.CREDITS_USED_CONTRACT_YTD / NULLIF(c.CONTRACT_MONTH, 0) * 12 - c.ANNUAL_COMMIT_CREDITS)
             * c.PRICE_PER_CREDIT_USD, 0) AS PROJECTED_SHORTFALL_USD,
       ROUND(c.COMMIT_ARR * GREATEST(0, 1 - c.BURN_PACE), 0) AS COMMIT_ARR_AT_RISK
FROM TRULINE.SYNTH.CONSUMPTION_MONTHLY c
WHERE c.MONTH = (SELECT MAX(MONTH) FROM TRULINE.SYNTH.CONSUMPTION_MONTHLY);

-- Scored play candidates: one row per account x play type, valued on one expected-ARR scale,
-- with owner rep, rep-cap overflow, escalation and partner intervention flags.
CREATE OR REPLACE DYNAMIC TABLE PLAY_CANDIDATES
  TARGET_LAG = '1 day' WAREHOUSE = DEFAULT_WH REFRESH_MODE = FULL
  COMMENT = 'Weekly play candidates scored by the CLAUDE.md play rules (thresholds in PLAY_PARAMS)'
AS
WITH p AS (
  SELECT MAX(IFF(PARAM = 'HEALTH_DROP_THRESHOLD', VALUE, NULL)) AS HEALTH_DROP,
         MAX(IFF(PARAM = 'LOW_UTIL_THRESHOLD', VALUE, NULL)) AS LOW_UTIL,
         MAX(IFF(PARAM = 'HIGH_UTIL_THRESHOLD', VALUE, NULL)) AS HIGH_UTIL,
         MAX(IFF(PARAM = 'TARGET_UTIL_AFTER_EXPANSION', VALUE, NULL)) AS TARGET_UTIL,
         MAX(IFF(PARAM = 'SEAT_EXPANSION_WIN_RATE', VALUE, NULL)) AS SEAT_WIN,
         MAX(IFF(PARAM = 'LOOKALIKE_MIN_PEER_SHARE', VALUE, NULL)) AS PEER_SHARE,
         MAX(IFF(PARAM = 'LOOKALIKE_MIN_PEERS', VALUE, NULL)) AS MIN_PEERS,
         MAX(IFF(PARAM = 'LOOKALIKE_WIN_RATE', VALUE, NULL)) AS LOOKALIKE_WIN,
         MAX(IFF(PARAM = 'CREDIT_LATE_CONTRACT_MONTH', VALUE, NULL)) AS LATE_MONTH,
         MAX(IFF(PARAM = 'MIN_PLAY_VALUE_USD', VALUE, NULL)) AS MIN_VALUE,
         MAX(IFF(PARAM = 'ESCALATE_VALUE_USD', VALUE, NULL)) AS ESCALATE_USD,
         MAX(IFF(PARAM = 'REP_WEEKLY_PLAY_CAP', VALUE, NULL)) AS REP_CAP,
         MAX(IFF(PARAM = 'PARTNER_NRR_FLOOR', VALUE, NULL)) AS NRR_FLOOR,
         MAX(IFF(PARAM = 'PARTNER_AT_RISK_SHARE_CEIL', VALUE, NULL)) AS AT_RISK_CEIL
  FROM TRULINE.CORE.PLAY_PARAMS),
act AS (SELECT * FROM TRULINE.CORE.ACCOUNT_CURRENT WHERE STATUS = 'Active' AND ARR_NOW > 0),
rescue AS (
  SELECT a.ACCOUNT_ID, 'Rescue' AS PLAY_FAMILY,
         IFF(a.HEALTH_SCORE_CHANGE_3M <= p.HEALTH_DROP, 'Renewal rescue', 'Proactive right-size') AS PLAY_TYPE,
         ARRAY_TO_STRING(ARRAY_CONSTRUCT_COMPACT(
           IFF(a.HEALTH_SCORE_CHANGE_3M <= p.HEALTH_DROP, 'Health score change (3 mo)', NULL),
           IFF(a.SEAT_UTILIZATION < p.LOW_UTIL AND a.SEAT_ARR > 0, 'Seat utilization', NULL)), ' + ') AS TRIGGER_METRICS,
         a.ARR_NOW * a.CHURN_PROB_90D AS VALUE_USD,
         'ARR x 90-day churn probability' AS VALUE_BASIS, NULL::VARCHAR AS PRODUCT_CODE
  FROM act a, p
  WHERE a.HEALTH_SCORE_CHANGE_3M <= p.HEALTH_DROP OR (a.SEAT_UTILIZATION < p.LOW_UTIL AND a.SEAT_ARR > 0)),
credits AS (
  SELECT c.ACCOUNT_ID, 'Credits' AS PLAY_FAMILY,
         CASE WHEN c.BURN_STATUS = 'Ahead of pace' THEN 'Credit top-up'
              WHEN c.CONTRACT_MONTH < p.LATE_MONTH THEN 'Credit adoption'
              ELSE 'Commit at risk' END AS PLAY_TYPE,
         'Burn pace' AS TRIGGER_METRICS,
         IFF(c.BURN_STATUS = 'Ahead of pace', c.PROJECTED_SHORTFALL_USD, c.COMMIT_ARR_AT_RISK) AS VALUE_USD,
         IFF(c.BURN_STATUS = 'Ahead of pace', 'Projected credit shortfall x price per credit',
             'Commit ARR x (1 - burn pace)') AS VALUE_BASIS, NULL::VARCHAR AS PRODUCT_CODE
  FROM TRULINE.CORE.CONSUMPTION_CURRENT c JOIN act a ON a.ACCOUNT_ID = c.ACCOUNT_ID, p
  WHERE c.BURN_STATUS IN ('Ahead of pace', 'Below pace')),
seat AS (
  SELECT a.ACCOUNT_ID, 'Expansion' AS PLAY_FAMILY, 'Seat expansion' AS PLAY_TYPE, 'Seat utilization' AS TRIGGER_METRICS,
         GREATEST(0, CEIL(a.ACTIVE_USERS / p.TARGET_UTIL) - a.SEATS) * (a.SEAT_ARR / NULLIF(a.SEATS, 0)) * p.SEAT_WIN AS VALUE_USD,
         'Seats to add x ARR per seat x win rate' AS VALUE_BASIS, NULL::VARCHAR AS PRODUCT_CODE
  FROM act a, p
  WHERE a.SEAT_UTILIZATION >= p.HIGH_UTIL AND a.SEATS > 0 AND a.SEAT_ARR > 0),
own AS (
  SELECT DISTINCT s.ACCOUNT_ID, s.PRODUCT_CODE FROM TRULINE.SYNTH.SUBSCRIPTIONS s
  WHERE s.STATUS LIKE 'Active%' AND s.PRODUCT_CODE <> 'CREDITS'),
cell AS (SELECT INDUSTRY_GROUP, SEGMENT, COUNT(*) AS PEERS FROM act GROUP BY 1, 2),
prod_cell AS (
  SELECT a.INDUSTRY_GROUP, a.SEGMENT, o.PRODUCT_CODE, COUNT(*) AS OWNERS
  FROM own o JOIN act a ON a.ACCOUNT_ID = o.ACCOUNT_ID GROUP BY 1, 2, 3),
prod_arr AS (
  SELECT a.INDUSTRY_GROUP, a.SEGMENT, s.PRODUCT_CODE, MEDIAN(s.CURRENT_ARR) AS TYPICAL_ARR
  FROM TRULINE.SYNTH.SUBSCRIPTIONS s JOIN act a ON a.ACCOUNT_ID = s.ACCOUNT_ID
  WHERE s.STATUS = 'Active' AND s.CURRENT_ARR > 0 GROUP BY 1, 2, 3),
suite_owned AS (
  SELECT o.ACCOUNT_ID, pr.PRODUCT_FAMILY FROM own o JOIN TRULINE.SYNTH.PRODUCTS pr ON pr.PRODUCT_CODE = o.PRODUCT_CODE
  WHERE pr.PRODUCT_NAME LIKE '%Suite'),
gap AS (
  SELECT a.ACCOUNT_ID, 'Expansion' AS PLAY_FAMILY, 'Look-alike product gap' AS PLAY_TYPE,
         'Peer product adoption' AS TRIGGER_METRICS, pa.TYPICAL_ARR * p.LOOKALIKE_WIN AS VALUE_USD,
         'Median peer ARR for the product x win rate' AS VALUE_BASIS, pc.PRODUCT_CODE
  FROM act a, p
  JOIN cell c ON TRUE
  JOIN prod_cell pc ON pc.INDUSTRY_GROUP = c.INDUSTRY_GROUP AND pc.SEGMENT = c.SEGMENT
  JOIN prod_arr pa ON pa.INDUSTRY_GROUP = pc.INDUSTRY_GROUP AND pa.SEGMENT = pc.SEGMENT AND pa.PRODUCT_CODE = pc.PRODUCT_CODE
  JOIN TRULINE.SYNTH.PRODUCTS pr ON pr.PRODUCT_CODE = pc.PRODUCT_CODE
  WHERE c.INDUSTRY_GROUP = a.INDUSTRY_GROUP AND c.SEGMENT = a.SEGMENT
    AND c.PEERS >= p.MIN_PEERS AND pc.OWNERS / c.PEERS >= p.PEER_SHARE
    AND a.BILLING_MODEL <> 'Consumption'
    AND NOT EXISTS (SELECT 1 FROM own o WHERE o.ACCOUNT_ID = a.ACCOUNT_ID AND o.PRODUCT_CODE = pc.PRODUCT_CODE)
    AND NOT EXISTS (SELECT 1 FROM suite_owned so WHERE so.ACCOUNT_ID = a.ACCOUNT_ID AND so.PRODUCT_FAMILY = pr.PRODUCT_FAMILY)
  QUALIFY ROW_NUMBER() OVER (PARTITION BY a.ACCOUNT_ID ORDER BY pa.TYPICAL_ARR DESC) = 1),
allp AS (SELECT * FROM rescue UNION ALL SELECT * FROM credits UNION ALL SELECT * FROM seat UNION ALL SELECT * FROM gap),
partner_health AS (
  SELECT PARTNER_ID,
         SUM(IFF(ARR_12M_AGO > 0, ARR_NOW, 0)) / NULLIF(SUM(ARR_12M_AGO), 0) AS PARTNER_NRR,
         SUM(IFF(STATUS = 'Active' AND RISK_BAND IN ('At Risk', 'Critical'), ARR_NOW, 0))
           / NULLIF(SUM(IFF(STATUS = 'Active', ARR_NOW, 0)), 0) AS PARTNER_AT_RISK_SHARE
  FROM TRULINE.CORE.ACCOUNT_CURRENT GROUP BY 1),
scored AS (
  SELECT 'C-' || LEFT(MD5(x.ACCOUNT_ID || x.PLAY_TYPE || a.AS_OF_MONTH), 12) AS CANDIDATE_ID,
         a.AS_OF_MONTH, x.PLAY_FAMILY, x.PLAY_TYPE, x.TRIGGER_METRICS, ROUND(x.VALUE_USD, 0) AS VALUE_USD, x.VALUE_BASIS,
         x.PRODUCT_CODE, pr.PRODUCT_NAME,
         a.ACCOUNT_ID, a.ACCOUNT_NAME, a.DOMAIN, a.IS_REAL_COMPANY, a.SEGMENT, a.INDUSTRY, a.BILLING_MODEL,
         a.PARTNER_ID, a.PARTNER_NAME, a.COVERAGE_MODEL, a.PAM_ID, a.PAM_NAME,
         a.PARTNER_REP_ID AS OWNER_REP_ID, a.REP_NAME AS OWNER_REP_NAME, a.REP_TITLE AS OWNER_REP_TITLE,
         a.ARR_NOW, a.HEALTH_SCORE, a.HEALTH_SCORE_CHANGE_3M, a.SEAT_UTILIZATION, a.CHURN_PROB_90D, a.RISK_BAND,
         a.DRIVER_1, a.DRIVER_2, a.MONTHS_TO_RENEWAL,
         cc.BURN_PACE, cc.CONTRACT_MONTH, cc.COMMIT_ARR,
         ph.PARTNER_NRR, ph.PARTNER_AT_RISK_SHARE,
         (ph.PARTNER_NRR < p.NRR_FLOOR OR ph.PARTNER_AT_RISK_SHARE > p.AT_RISK_CEIL) AS PARTNER_NEEDS_INTERVENTION,
         p.ESCALATE_USD, p.REP_CAP, p.MIN_VALUE
  FROM allp x
  JOIN act a ON a.ACCOUNT_ID = x.ACCOUNT_ID
  LEFT JOIN TRULINE.CORE.CONSUMPTION_CURRENT cc ON cc.ACCOUNT_ID = x.ACCOUNT_ID
  LEFT JOIN TRULINE.SYNTH.PRODUCTS pr ON pr.PRODUCT_CODE = x.PRODUCT_CODE
  JOIN partner_health ph ON ph.PARTNER_ID = a.PARTNER_ID, p
  WHERE x.VALUE_USD >= p.MIN_VALUE)
SELECT s.* EXCLUDE (ESCALATE_USD, REP_CAP, MIN_VALUE),
       ROW_NUMBER() OVER (PARTITION BY s.OWNER_REP_ID ORDER BY s.VALUE_USD DESC, s.MONTHS_TO_RENEWAL) AS REP_RANK,
       ROW_NUMBER() OVER (PARTITION BY s.PARTNER_ID ORDER BY s.VALUE_USD DESC, s.MONTHS_TO_RENEWAL) AS PARTNER_RANK,
       ROW_NUMBER() OVER (PARTITION BY COALESCE(s.PAM_ID, 'LONG_TAIL') ORDER BY s.VALUE_USD DESC, s.MONTHS_TO_RENEWAL) AS PAM_RANK,
       REP_RANK > s.REP_CAP AS REP_OVER_CAP,
       CASE WHEN s.VALUE_USD > s.ESCALATE_USD THEN 'Value over threshold'
            WHEN REP_RANK > s.REP_CAP THEN 'Rep over weekly cap'
            WHEN s.PARTNER_NEEDS_INTERVENTION THEN 'Partner needs intervention' END AS ESCALATION_REASON,
       IFF(ESCALATION_REASON IS NULL, 'Rep', IFF(s.PAM_ID IS NULL, 'Coverage ops', 'PAM')) AS ROUTED_TO
FROM scored s;

-- Writes from the app and the agent.
CREATE TABLE IF NOT EXISTS PLAYS (
  PLAY_ID VARCHAR DEFAULT 'PL-' || LEFT(UUID_STRING(), 8), CANDIDATE_ID VARCHAR, WEEK_OF DATE,
  ACCOUNT_ID VARCHAR, PARTNER_ID VARCHAR, PLAY_TYPE VARCHAR, OWNER_REP_ID VARCHAR, ROUTED_TO VARCHAR,
  VALUE_USD NUMBER(18, 0), STATUS VARCHAR, NOTE VARCHAR,
  CREATED_BY VARCHAR DEFAULT CURRENT_USER(), CREATED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP());

CREATE TABLE IF NOT EXISTS AUDIT_LOG (
  EVENT_ID VARCHAR DEFAULT UUID_STRING(), EVENT_TS TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP(),
  USER_NAME VARCHAR DEFAULT CURRENT_USER(), ROLE_NAME VARCHAR DEFAULT CURRENT_ROLE(),
  ACTION VARCHAR, OBJECT_TYPE VARCHAR, OBJECT_ID VARCHAR, DETAILS VARIANT,
  QUERY_TAG VARCHAR, SESSION_ID NUMBER DEFAULT CURRENT_SESSION()::NUMBER);

-- Claim checker storage: each document's citable facts, and the checked documents.
CREATE TABLE IF NOT EXISTS DOC_FACTS (
  DOC_ID VARCHAR, FACT_ID VARCHAR, LABEL VARCHAR, VALUE FLOAT, TEXT_VALUE VARCHAR, DISPLAY VARCHAR, UNIT VARCHAR,
  METRIC VARCHAR, SOURCE_OBJECT VARCHAR, FILTERS VARCHAR, INTERNAL_ONLY BOOLEAN, QUERY_ID VARCHAR,
  CREATED_BY VARCHAR DEFAULT CURRENT_USER(), CREATED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP());

CREATE TABLE IF NOT EXISTS DOCUMENTS (
  DOC_ID VARCHAR, DOC_TYPE VARCHAR, SUBJECT_ID VARCHAR, AUDIENCE VARCHAR, DRAFT VARCHAR, RENDERED VARCHAR,
  CHECK_STATUS VARCHAR, VIOLATIONS VARIANT,
  CREATED_BY VARCHAR DEFAULT CURRENT_USER(), CREATED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP());

-- Who may see which partners. Row access policies read USER_PARTNER_ACCESS.
CREATE TABLE IF NOT EXISTS USER_SCOPE (USER_NAME VARCHAR, PERSONA VARCHAR, SCOPE VARCHAR, PAM_ID VARCHAR, PARTNER_ID VARCHAR);
CREATE OR REPLACE VIEW USER_PARTNER_ACCESS AS
SELECT u.USER_NAME, u.PERSONA, p.PARTNER_ID
FROM USER_SCOPE u JOIN TRULINE.SYNTH.PARTNERS p
  ON (u.SCOPE = 'PAM' AND p.PAM_ID = u.PAM_ID)
  OR (u.SCOPE = 'PARTNER' AND p.PARTNER_ID = u.PARTNER_ID)
  OR u.SCOPE = 'ALL';
