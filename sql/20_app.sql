-- App layer: the only objects personas can read. Run as ATTENDEE_ROLE after 10_core.sql.
-- Every partner-scoped view carries RAP_PARTNER_SCOPE (row access by CURRENT_USER() -> USER_SCOPE);
-- internal model fields are masked for partner users. No SIM_* column is exposed.
-- Policies key on the user, not roles: secondary roles (e.g. ACCOUNTADMIN) must not widen access.
CREATE SCHEMA IF NOT EXISTS TRULINE.APP;
USE SCHEMA TRULINE.CORE;

CREATE ROW ACCESS POLICY IF NOT EXISTS RAP_PARTNER_SCOPE AS (P_ID VARCHAR) RETURNS BOOLEAN -> TRUE;
ALTER ROW ACCESS POLICY RAP_PARTNER_SCOPE SET BODY ->
  EXISTS (SELECT 1 FROM TRULINE.CORE.USER_PARTNER_ACCESS u
          WHERE u.USER_NAME = CURRENT_USER() AND u.PARTNER_ID = P_ID);
ALTER ROW ACCESS POLICY RAP_PARTNER_SCOPE SET COMMENT = 'Rows visible only for partners in the current user''s coverage (CORE.USER_SCOPE)';

CREATE ROW ACCESS POLICY IF NOT EXISTS RAP_OWN_ROWS AS (U VARCHAR) RETURNS BOOLEAN -> TRUE;
ALTER ROW ACCESS POLICY RAP_OWN_ROWS SET BODY ->
  U = CURRENT_USER()
  OR EXISTS (SELECT 1 FROM TRULINE.CORE.USER_SCOPE s WHERE s.USER_NAME = CURRENT_USER() AND s.SCOPE = 'ALL');
ALTER ROW ACCESS POLICY RAP_OWN_ROWS SET COMMENT = 'Users see their own audit, fact and document rows; coverage ops sees all';

CREATE MASKING POLICY IF NOT EXISTS MP_INTERNAL_NUMBER AS (V FLOAT) RETURNS FLOAT -> V;
ALTER MASKING POLICY MP_INTERNAL_NUMBER SET BODY ->
  IFF(EXISTS (SELECT 1 FROM TRULINE.CORE.USER_SCOPE s WHERE s.USER_NAME = CURRENT_USER() AND s.SCOPE = 'PARTNER'), NULL, V);
CREATE MASKING POLICY IF NOT EXISTS MP_INTERNAL_TEXT AS (V VARCHAR) RETURNS VARCHAR -> V;
ALTER MASKING POLICY MP_INTERNAL_TEXT SET BODY ->
  IFF(EXISTS (SELECT 1 FROM TRULINE.CORE.USER_SCOPE s WHERE s.USER_NAME = CURRENT_USER() AND s.SCOPE = 'PARTNER'), '*** internal ***', V);

USE SCHEMA TRULINE.APP;

CREATE OR REPLACE SECURE VIEW ACCOUNTS
  WITH ROW ACCESS POLICY TRULINE.CORE.RAP_PARTNER_SCOPE ON (PARTNER_ID)
  COMMENT = 'Customer accounts at the latest month (Sep 2026), scoped to the user''s partners'
AS SELECT * FROM TRULINE.CORE.ACCOUNT_CURRENT;
ALTER VIEW ACCOUNTS MODIFY COLUMN CHURN_PROB_90D SET MASKING POLICY TRULINE.CORE.MP_INTERNAL_NUMBER;
ALTER VIEW ACCOUNTS MODIFY COLUMN DRIVER_1 SET MASKING POLICY TRULINE.CORE.MP_INTERNAL_TEXT;
ALTER VIEW ACCOUNTS MODIFY COLUMN DRIVER_2 SET MASKING POLICY TRULINE.CORE.MP_INTERNAL_TEXT;

CREATE OR REPLACE SECURE VIEW ACCOUNT_MONTHLY
  WITH ROW ACCESS POLICY TRULINE.CORE.RAP_PARTNER_SCOPE ON (PARTNER_ID)
  COMMENT = 'Monthly ARR bridge, usage and health per account (Oct 2023 - Sep 2026)'
AS SELECT MONTH, ACCOUNT_ID, PARTNER_ID, BILLING_MODEL, START_ARR, NEW_ARR, EXPANSION_ARR, CONTRACTION_ARR, CHURN_ARR,
          MIGRATED_OUT_ARR, MIGRATED_IN_ARR, END_ARR, SEAT_ARR, CONSUMPTION_ARR, OVERAGE_REVENUE, SEATS, ACTIVE_USERS,
          SEAT_UTILIZATION, CREDITS_CONSUMED, HEALTH_SCORE, HEALTH_SCORE_CHANGE_3M, RISK_BAND, MONTHS_TO_RENEWAL
   FROM TRULINE.SYNTH.ACCOUNT_MONTHLY;

CREATE OR REPLACE SECURE VIEW SUBSCRIPTIONS
  WITH ROW ACCESS POLICY TRULINE.CORE.RAP_PARTNER_SCOPE ON (PARTNER_ID)
  COMMENT = 'Current product subscriptions per account'
AS SELECT s.SUBSCRIPTION_ID, s.ACCOUNT_ID, a.PARTNER_ID, s.PRODUCT_CODE, s.BILLING_MODEL, s.STATUS, s.START_MONTH,
          s.END_MONTH, s.CURRENT_SEATS, s.UNIT_PRICE_USD, s.ANNUAL_COMMIT_CREDITS, s.CURRENT_ARR
   FROM TRULINE.SYNTH.SUBSCRIPTIONS s JOIN TRULINE.SYNTH.ACCOUNTS a ON a.ACCOUNT_ID = s.ACCOUNT_ID;

CREATE OR REPLACE SECURE VIEW PARTNERS
  WITH ROW ACCESS POLICY TRULINE.CORE.RAP_PARTNER_SCOPE ON (PARTNER_ID)
  COMMENT = 'Reseller partners with coverage model and Truline PAM'
AS SELECT p.PARTNER_ID, p.PARTNER_NAME, p.TIER, p.REGION, p.HQ_COUNTRY, p.SPECIALIZATION, p.PARTNER_SINCE_YEAR,
          p.CURRENT_MANAGED_ARR, p.PARTNER_ARR_RANK, p.COVERAGE_MODEL, p.PAM_ID, k.PAM_NAME, k.EMAIL AS PAM_EMAIL
   FROM TRULINE.SYNTH.PARTNERS p LEFT JOIN TRULINE.SYNTH.TRULINE_PAMS k ON k.PAM_ID = p.PAM_ID;

CREATE OR REPLACE SECURE VIEW PARTNER_REPS
  WITH ROW ACCESS POLICY TRULINE.CORE.RAP_PARTNER_SCOPE ON (PARTNER_ID)
  COMMENT = 'Partner sales reps and their books'
AS SELECT REP_ID, PARTNER_ID, REP_NAME, TITLE, SEGMENT_FOCUS, REGION, EMAIL, BOOK_ACTIVE_ACCOUNTS, BOOK_ARR
   FROM TRULINE.SYNTH.PARTNER_REPS;

CREATE OR REPLACE SECURE VIEW CONSUMPTION
  WITH ROW ACCESS POLICY TRULINE.CORE.RAP_PARTNER_SCOPE ON (PARTNER_ID)
  COMMENT = 'Credit contracts at the latest month: burn pace, shortfall, commit at risk'
AS SELECT * FROM TRULINE.CORE.CONSUMPTION_CURRENT;

CREATE OR REPLACE SECURE VIEW PLAY_CANDIDATES
  WITH ROW ACCESS POLICY TRULINE.CORE.RAP_PARTNER_SCOPE ON (PARTNER_ID)
  COMMENT = 'This week''s scored plays with owner rep and escalation routing'
AS SELECT * FROM TRULINE.CORE.PLAY_CANDIDATES;
ALTER VIEW PLAY_CANDIDATES MODIFY COLUMN CHURN_PROB_90D SET MASKING POLICY TRULINE.CORE.MP_INTERNAL_NUMBER;
ALTER VIEW PLAY_CANDIDATES MODIFY COLUMN ESCALATION_REASON SET MASKING POLICY TRULINE.CORE.MP_INTERNAL_TEXT;

CREATE OR REPLACE SECURE VIEW PLAYS
  WITH ROW ACCESS POLICY TRULINE.CORE.RAP_PARTNER_SCOPE ON (PARTNER_ID)
  COMMENT = 'Approved and delegated plays'
AS SELECT * FROM TRULINE.CORE.PLAYS;

CREATE OR REPLACE SECURE VIEW AUDIT_LOG
  WITH ROW ACCESS POLICY TRULINE.CORE.RAP_OWN_ROWS ON (USER_NAME)
  COMMENT = 'Every agent and user action (own rows; coverage ops sees all)'
AS SELECT * FROM TRULINE.CORE.AUDIT_LOG;

CREATE OR REPLACE SECURE VIEW DOC_FACTS
  WITH ROW ACCESS POLICY TRULINE.CORE.RAP_OWN_ROWS ON (CREATED_BY)
  COMMENT = 'Citable facts per generated document, with source query IDs'
AS SELECT * FROM TRULINE.CORE.DOC_FACTS;

CREATE OR REPLACE SECURE VIEW DOCUMENTS
  WITH ROW ACCESS POLICY TRULINE.CORE.RAP_OWN_ROWS ON (CREATED_BY)
  COMMENT = 'Generated documents with claim-check status'
AS SELECT * FROM TRULINE.CORE.DOCUMENTS;

CREATE OR REPLACE SECURE VIEW PRODUCTS COMMENT = 'Truline product catalog'
AS SELECT PRODUCT_CODE, PRODUCT_NAME, PRODUCT_FAMILY, PRICING_MODEL, PRICE_UNIT, LIST_PRICE_USD, DESCRIPTION
   FROM TRULINE.SYNTH.PRODUCTS;

CREATE OR REPLACE SECURE VIEW PLAY_PARAMS COMMENT = 'Play-rule thresholds in force'
AS SELECT * FROM TRULINE.CORE.PLAY_PARAMS;

CREATE OR REPLACE SECURE VIEW MY_SCOPE COMMENT = 'Who am I and what can I see (drives the identity badge)'
AS SELECT CURRENT_USER() AS USER_NAME, CURRENT_ROLE() AS ROLE_NAME,
          (SELECT ANY_VALUE(PERSONA) FROM TRULINE.CORE.USER_SCOPE WHERE USER_NAME = CURRENT_USER()) AS PERSONA,
          (SELECT ANY_VALUE(PAM_ID) FROM TRULINE.CORE.USER_SCOPE WHERE USER_NAME = CURRENT_USER()) AS PAM_ID,
          (SELECT COUNT(*) FROM TRULINE.APP.PARTNERS) AS PARTNERS_VISIBLE,
          (SELECT COUNT(*) FROM TRULINE.SYNTH.PARTNERS) AS PARTNERS_TOTAL,
          (SELECT MAX(AS_OF_MONTH) FROM TRULINE.CORE.ACCOUNT_CURRENT) AS DATA_AS_OF;
